class LocalSequentialSampler:
    """HF NF4 functional path, preserving the admitted policy with CPU trainable snapshots."""

    def __init__(self, bundle: Any, *, protocol_sha256: str, image: dict, sampling: dict):
        self.bundle, self.protocol_sha256, self.image, self.sampling = bundle, protocol_sha256, image, sampling
        self.versions: dict[int, dict] = {}
        self.pending: list[dict] = []
        self.engine_steps = 0

    def _snapshot(self) -> dict:
        owned = {id(p) for group in self.bundle.params.values() for p in group}
        return {n: p.detach().cpu().clone() for n, p in self.bundle.model.named_parameters() if id(p) in owned}

    def _load(self, values: dict) -> None:
        import torch

        owned = {id(p) for group in self.bundle.params.values() for p in group}
        live = {n: p for n, p in self.bundle.model.named_parameters() if id(p) in owned}
        if live.keys() != values.keys():
            raise RuntimeError("v16b HF: trainable inventory changed")
        with torch.no_grad():
            for name, value in values.items():
                live[name].copy_(value.to(device=live[name].device, dtype=live[name].dtype))

    def add_version(self, bundle: Any, version: int) -> str:
        from .rl import policy_sha256

        self.release_idle_versions()
        if version in self.versions or len(self.versions) >= 2:
            raise RuntimeError("v16b HF: duplicate version or more than two live policies")
        policy = policy_sha256(bundle)
        self.versions[version] = {"policy_sha256": policy, "weights": self._snapshot(), "refcount": 0}
        return policy

    def submit(self, request: dict) -> None:
        entry = self.versions[request["policy_version"]]
        if request["policy_sha256"] != entry["policy_sha256"]:
            raise RuntimeError("v16b HF: admission hash differs from its snapshot")
        if any(r["request_id"] == request["request_id"] for r in self.pending):
            raise RuntimeError("v16b HF: duplicate request")
        self.pending.append(request)
        entry["refcount"] += 1

    def step(self) -> list[tuple[dict, dict]]:
        if not self.pending:
            return []
        request = self.pending[0]
        version = request["policy_version"]
        entry = self.versions[version]
        current = self._snapshot()
        self._load(entry["weights"])
        try:
            sampling = dict(request.get("sampling", self.sampling))
            args = SimpleNamespace(max_num_seqs=1, context_limit=24576, max_num_batched_tokens=24576,
                                   image_cfg=self.image, policy_sha256=entry["policy_sha256"],
                                   protocol_sha256=self.protocol_sha256, sampling=sampling, loop_stop=False)
            stats = StreamStats()
            result = list(hf_single_stream_builder(self.bundle, args, stats)([request], stats, None))
            if len(result) != 1:
                raise RuntimeError("v16b HF: exactly one completed request required")
            _, output = result[0]
            full = sampling["top_p"] == 1.0 and sampling["top_k"] == 0
            output["generation"].update(probability_space="processed-full-vocab-v1" if full else "processed-truncated-b2",
                kind=request["kind"], policy_version=version, visual_version=version,
                mixed_version=False, preempted=False, lora_int_id=None, admit_step=request["admit_step"],
                finish_step=self.engine_steps + stats.steps, request_sha256=request["request_sha256"])
            for key in ("baseline_receipt", "obs_baseline_receipt"):
                if key in request:
                    output["generation"][key] = request[key]
        finally:
            self._load(current)
        self.pending.pop(0)
        entry["refcount"] -= 1
        self.engine_steps += stats.steps
        return [(request, output)]

    def has_unfinished_requests(self) -> bool:
        return bool(self.pending)

    def prefill_barrier(self) -> bool:
        # Deferred HF work has a complete immutable snapshot, including vision and Mergers.
        return True

    def live_registry(self) -> dict:
        return {str(v): {"policy_sha256": e["policy_sha256"], "refcount": e["refcount"]}
                for v, e in self.versions.items()}

    def release(self) -> None:
        if self.has_unfinished_requests():
            raise RuntimeError("v16b HF: cannot release pending admission snapshots")
        self.versions.clear()

    def release_idle_versions(self, *, keep: int | None = None) -> None:
        for version, entry in list(self.versions.items()):
            if entry["refcount"] == 0 and version != keep:
                del self.versions[version]


class V16bScheduler:
    def __init__(self, sampler: Any, *, plan: dict, protocol: dict, items: Any, grade: Callable | None,
                 verify: Callable | None, out: Path, local_sequential: bool = False,
                 callbacks: RuntimeCallbacks, restore: bool = False):
        self.sampler, self.plan, self.protocol = sampler, plan, protocol
        self.grade, self.verify, self.callbacks = grade, verify, callbacks
        self.v18b = protocol.get("version") == "error-note-v18b"
        self.v18 = protocol.get("version") in {"error-note-v18", "error-note-v18b"}
        self.v17 = protocol.get("version") in {"error-note-v17", "error-note-v18", "error-note-v18b"}
        self._submitting = False
        self.admission_wait_seconds = 0.0
        self._heartbeat_at = 0.0
        self.host_stage_seconds = {"request_preparation": 0.0, "completion_validation": 0.0,
                                   "row_construction": 0.0, "journal_serialization": 0.0}
        self.out, self.local_sequential = Path(out), local_sequential
        self.out.mkdir(parents=True, exist_ok=True)
        if isinstance(items, dict):
            by_id = items
        else:
            flattened = [item for group in items for item in group] if items and isinstance(items[0], list) else items
            by_id = {item["problem_id"]: item for item in flattened}
        blocks = plan.get("blocks")
        if blocks is None:
            order = plan.get("problem_ids", list(by_id))
            size = plan.get("block_size", 16)
            blocks = [order[i:i + size] for i in range(0, len(order), size)]
        if not isinstance(blocks, list):
            raise ValueError("v16b runtime: block plan must be a list")
        self.blocks: list[list[dict]] = []
        for block in blocks:
            members = block.get("problem_ids", block.get("items")) if isinstance(block, dict) else block
            if not isinstance(members, list):
                raise ValueError("v16b runtime: block members must be a list")
            self.blocks.append([by_id[p] if isinstance(p, str) else p for p in members])
        ids = [item["problem_id"] for block in self.blocks for item in block]
        if not ids or len(ids) != len(set(ids)) or any(not 1 <= len(b) <= 16 for b in self.blocks):
            raise ValueError("v16b runtime: unique nonempty blocks of at most sixteen required")
        self.records: dict[str, dict] = {pid: {} for pid in ids}
        self.history: list[dict] = []
        self.requests: dict[str, dict] = {}
        self._rollback_started: dict[str, dict] = {}
        self.closed: dict[str, dict] = {}
        self.stages: dict[str, list[str]] = {}
        self.committed: list[int] = []
        self.row_settlements: dict[str, dict] = {}
        self.version = 0
        self.generation_seconds = 0.0
        self.last_update = len(self.blocks) + 2
        self.plan_sha256 = _digest(plan)
        self.protocol_sha256 = protocol.get("protocol_sha256", _digest(protocol))
        if (self.out / "requests.jsonl").exists() and not restore:
            raise RuntimeError("v16b runtime: existing request journal requires explicit drain restore")

    def _append(self, event: dict) -> None:
        serialization_started = time.perf_counter()
        with (self.out / "requests.jsonl").open("a", encoding="utf-8") as stream:
            stream.write(json.dumps(event, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        self.host_stage_seconds["journal_serialization"] += time.perf_counter() - serialization_started

    def _submit_stage(self, block: int, kind: str, version: int) -> None:
        if not 0 <= block < len(self.blocks):
            return
        key = f"{block}:{kind}"
        if key in self.stages:
            raise RuntimeError("v16b runtime: a stage may only be admitted once")
        self.stages[key] = []
        for item in self.blocks[block]:
            pid = item["problem_id"]
            preparation_started = time.perf_counter()
            request = self.callbacks.make_request(item, kind, version, self.records[pid])
            self.host_stage_seconds["request_preparation"] += time.perf_counter() - preparation_started
            if request is None:
                if kind == "RESOLVE" and hasattr(self.sampler, "forget_item"):
                    self.sampler.forget_item(pid)
                continue
            request = dict(request)
            request.update(kind=kind, block_id=block, problem_id=pid, policy_version=version,
                           protocol_sha256=self.protocol_sha256, admit_step=self.sampler.engine_steps)
            registry = self.sampler.live_registry()
            request["policy_sha256"] = registry[str(version)]["policy_sha256"]
            if self.callbacks.baseline is not None and kind in ("T1", "OBS"):
                receipt = self.callbacks.baseline(item, kind, list(self.history), block - 2)
                request["baseline_receipt" if kind == "T1" else "obs_baseline_receipt"] = receipt
            base_sha = single_request_sha256(request)
            evidence = {k: request[k] for k in ("kind", "policy_version", "policy_sha256", "protocol_sha256")}
            for name in ("sampling", "baseline_receipt", "obs_baseline_receipt"):
                if name in request:
                    evidence[name] = request[name]
            request["request_sha256"] = _digest({"input_request_sha256": base_sha, **evidence})
            rid = request["request_id"]
            if rid in self.requests:
                raise RuntimeError("v16b runtime: duplicate request identity")
            stored = single_request_binding(request) | evidence | {"request_sha256": request["request_sha256"]}
            previous = self._rollback_started.get(rid)
            if previous is not None and previous != _pin(stored):
                raise RuntimeError("v16b runtime: rollback changed the original policy, seed or request")
            prepared = None
            if self.v17 and not self.local_sequential:
                preparation_started = time.perf_counter()
                prepared = self.sampler.prepare_request_v17(request)
                self.host_stage_seconds["request_preparation"] += time.perf_counter() - preparation_started
                wait_started = time.perf_counter()
                while not self.sampler.can_submit_v17(prepared):
                    if not self.sampler.has_unfinished_requests():
                        raise RuntimeError("CAPACITY_INSUFFICIENT: no live request can release training KV")
                    self.step()
                self.admission_wait_seconds += time.perf_counter() - wait_started
                request["admit_step"] = self.sampler.engine_steps
            self._append({"status": "STARTED", **stored})
            self.requests[rid] = stored
            self.stages[key].append(rid)
            if prepared is None:
                self.sampler.submit(request)
            else:
                self.sampler.submit(request, prepared=prepared)

    def submit_for_version(self, v: int) -> None:
        if v != self.version or v > self.last_update:
            raise ValueError("v16b runtime: admission version differs from the update cursor")
        self._submitting = True
        try:
            if v == 0:
                self._submit_stage(0, "T1", v)
                self._submit_stage(0, "OBS", v)
            self._submit_stage(v + 1, "T1", v)
            self._submit_stage(v + 1, "OBS", v)
            self._submit_stage(v - 1, "NOTE", v)
            self._submit_stage(v - 2, "RESOLVE", v)
        except BaseException:
            # An incomplete stage is never a closed admission/checkpoint boundary.
            raise
        else:
            self._submitting = False

    def _closed_stage(self, block: int, kind: str) -> bool:
        if not 0 <= block < len(self.blocks):
            return True
        key = f"{block}:{kind}"
        return key in self.stages and all(rid in self.closed for rid in self.stages[key])

    def ready_for_update(self, v: int) -> bool:
        return (not self._submitting and v == self.version and all(self._closed_stage(b, kind) for b, kind in
                ((v, "T1"), (v, "OBS"), (v - 1, "NOTE"), (v - 3, "RESOLVE")))
                and self.sampler.prefill_barrier())

    def step(self) -> list[dict]:
        completed = []
        started = time.perf_counter()
        outputs = self.sampler.step()
        self.generation_seconds += time.perf_counter() - started
        now = time.perf_counter()
        if (self.v17 and not self.local_sequential and hasattr(self.sampler, "heartbeat_v17")
                and now - self._heartbeat_at >= 60):
            self.sampler.admission_wait_seconds = self.admission_wait_seconds
            heartbeat = {"schema": "v17-train-heartbeat-v1", "slot": self.version,
                         "engine_steps": self.sampler.engine_steps, "clock": "time.perf_counter",
                         "observed_at": now, **self.sampler.heartbeat_v17()}
            _write(self.out / "train-heartbeat.json", heartbeat)
            print("V17_TRAIN_HEARTBEAT " + json.dumps(heartbeat, sort_keys=True), flush=True)
            self._heartbeat_at = now
        for request, output in outputs:
            rid, pid, kind = request["request_id"], request["problem_id"], request["kind"]
            if rid not in self.requests or rid in self.closed:
                raise RuntimeError("v16b runtime: unknown or duplicate completion")
            generation = output["generation"]
            for field in ("request_sha256", "policy_sha256", "policy_version", "seed"):
                if generation.get(field) != request[field]:
                    raise RuntimeError(f"v16b runtime: completion changed admission {field}")
            record = self.records[pid]
            record[kind.lower()] = output
            item = self.blocks[request["block_id"]][[i["problem_id"] for i in self.blocks[request["block_id"]]].index(pid)]
            if self.callbacks.complete is not None:
                validation_started = time.perf_counter()
                updates = self.callbacks.complete(item, kind, output, record)
                self.host_stage_seconds["completion_validation"] += time.perf_counter() - validation_started
                if updates:
                    record.update(updates)
            self.closed[rid] = output
            _write(self.out / "items" / (_digest(pid) + ".json"), {"problem_id": pid, **record})
            self._append({"status": "COMPLETED", "request_id": rid, "request_sha256": request["request_sha256"],
                          "output_sha256": _digest(output)})
            completed.append({"request_id": rid, "kind": kind, "output": output})
        return completed

    def rows_for_update(self, v: int) -> list[dict]:
        if not self.ready_for_update(v):
            raise RuntimeError("v16b runtime: update dependencies or visual-prefill barrier are open")
        construction_started = time.perf_counter()
        rows = []
        for block, kind in ((v, "T1"), (v, "OBS"), (v - 1, "NOTE"), (v - 3, "RESOLVE")):
            if 0 <= block < len(self.blocks):
                for item in self.blocks[block]:
                    rows.extend(self.callbacks.rows(kind, item, self.records[item["problem_id"]]))
        self.host_stage_seconds["row_construction"] += time.perf_counter() - construction_started
        payload = {"version": v, "rows": rows}
        path = self.out / f"rows-{v}.json"
        if path.exists() and json.loads(path.read_text()) != payload:
            raise RuntimeError("v16b runtime: sealed rows changed")
        _write(path, payload)
        _write(path.with_suffix(".sha256.json"), {"sha256": _digest(payload)})
        return rows

    def update_contract(self, v: int) -> dict:
        def members(block: int, kind: str) -> list[str]:
            return [self.requests[rid]["problem_id"] for rid in self.stages.get(f"{block}:{kind}", [])]
        receipts = {}
        rewards = {}
        for kind in ("T1", "OBS"):
            for rid in self.stages.get(f"{v}:{kind}", []):
                request = self.requests[rid]
                key = "baseline_receipt" if kind == "T1" else "obs_baseline_receipt"
                training_kind = "RL" if kind == "T1" else kind
                if key in request:
                    receipts[f"{training_kind}:{request['problem_id']}"] = request[key]
                record = self.records[request["problem_id"]]
                frozen = record.get("reward_values", {}).get(training_kind)
                if frozen is not None:
                    rewards[f"{training_kind}:{request['problem_id']}"] = frozen
        return self.protocol | {"phase": "rl", "block_id": v, "expected_problem_ids": members(v, "T1"),
            "expected_obs_problem_ids": members(v, "OBS"), "note_problem_ids": members(v - 1, "NOTE"),
            "resolve_problem_ids": members(v - 3, "RESOLVE"), "baseline_receipts": receipts, "reward_values": rewards}

    def commit_history(self, v: int) -> None:
        if v in self.committed:
            raise RuntimeError("v16b runtime: duplicate history commit")
        if v < len(self.blocks):
            for item in self.blocks[v]:
                record = self.records[item["problem_id"]]
                for kind in ("T1", "OBS"):
                    outcome = record.get(kind.lower(), {})
                    receipt = record.get("reward_receipt" if kind == "T1" else "obs_reward_receipt", {})
                    reward = receipt.get("reward") if self.v18 else record.get("reward" if kind == "T1" else "obs_score")
                    if self.v18 and receipt.get("pg") is not True:
                        continue
                    if isinstance(reward, dict):
                        reward = reward.get("score")
                    if reward is not None:
                        self.history.append({"problem_id": item["problem_id"], "source": item.get("source"),
                            "layer": item.get("layer"), "kind": kind, "reward": reward, "block": v,
                            "committed": True, "output_sha256": _digest(outcome),
                            **({"pg": True, "task": OBS_TASK_V18} if self.v18 and kind == "OBS" else {})})
        self.committed.append(v)

    def drain(self) -> None:
        while self.sampler.has_unfinished_requests():
            self.step()
        if set(self.requests) != set(self.closed):
            raise RuntimeError("v16b runtime: drain left STARTED requests without COMPLETED")

    def pending_descriptors(self) -> list[dict]:
        result = []
        for rid in sorted(self.closed):
            request = self.requests[rid]
            block, kind = request["block_id"], request["kind"]
            update = block if kind in ("T1", "OBS") else block + (1 if kind == "NOTE" else 3)
            if update >= self.version:
                result.append({"request_id": rid, "consume_version": update, "output_sha256": _digest(self.closed[rid])})
        return result

    def settle_rows(self, version: int, rows: list[dict], stats: dict) -> None:
        if not self.v18:
            return
        ids = [row["row_id"] for row in rows]
        consumed = stats.get("consumed_row_ids")
        if not isinstance(consumed, list) or len(ids) != len(set(ids)) or len(consumed) != len(set(consumed)):
            raise RuntimeError("v18 closure: unique row IDs and actual consumption telemetry required")
        quarantine = stats.get("row_quarantine") or {}
        rejected = quarantine.get("rejected_rows", [])
        rejected_ids = [row["row_id"] for row in rejected]
        originals = {row["row_id"]: row for row in rows}
        if rejected and (not self.v18b or quarantine.get("status") != "CONTINUE"
                or len(rejected_ids) != len(set(rejected_ids)) or set(rejected_ids) - set(ids)
                or set(rejected_ids) & set(consumed)
                or len(rejected_ids) * 2 > sum(row.get("kind") in {"A1", "C", "N"} for row in rows)
                or quarantine.get("attempted_rows") != len(rows)
                or quarantine.get("admitted_row_ids") != [rid for rid in ids if rid not in set(rejected_ids)]
                or any(originals[row["row_id"]].get("kind") not in {"A1", "C", "N"}
                       or row.get("kind") != originals[row["row_id"]].get("kind")
                       or row.get("source_row_sha256") != _digest(originals[row["row_id"]]) for row in rejected)):
            raise RuntimeError("v18b closure: invalid auxiliary quarantine evidence")
        held = bool(stats.get("HOLD", stats.get("hold", False)))
        if set(consumed) - set(ids) or (held and consumed) or (not held and set(consumed) | set(rejected_ids) != set(ids)):
            raise RuntimeError("v18 closure: accepted rows are neither consumed nor explicitly held")
        self.row_settlements[str(version)] = {"row_ids": ids, "consumed_row_ids": consumed,
            "discarded_row_ids": ids if held else rejected_ids, "hold_reason": stats.get("hold_reason") if held else None,
            **({"quarantined_row_ids": rejected_ids, "row_quarantine_sha256": _digest(quarantine)} if rejected else {}),
            "optimizer_step": stats.get("optimizer_step"),
            "generation_versions": {r["row_id"]: r.get("policy_version", r.get("generation", {}).get("policy_version")) for r in rows}}

    def terminal_closure(self, consumed_row_ids: list[str] | None = None) -> dict:
        if not self.v18:
            raise ValueError("v18 closure: versioned runtime required")
        if (self.version != self.last_update + 1 or self.sampler.has_unfinished_requests()
                or set(self.requests) != set(self.closed) or self.pending_descriptors()
                or any(not self._closed_stage(b, kind) for b in range(len(self.blocks))
                       for kind in ("T1", "OBS", "NOTE", "RESOLVE"))):
            raise RuntimeError("v18 closure: generation or delayed rows remain open")
        if set(self.row_settlements) != {str(v) for v in range(self.last_update + 1)}:
            raise RuntimeError("v18 closure: missing update settlement")
        rows = [rid for entry in self.row_settlements.values() for rid in entry["row_ids"]]
        consumed = [rid for entry in self.row_settlements.values() for rid in entry["consumed_row_ids"]]
        discarded = [rid for entry in self.row_settlements.values() for rid in entry["discarded_row_ids"]]
        quarantined = [rid for entry in self.row_settlements.values() for rid in entry.get("quarantined_row_ids", [])]
        if len(rows) != len(set(rows)) or set(rows) != set(consumed) | set(discarded) or set(consumed) & set(discarded):
            raise RuntimeError("v18 closure: duplicate or unsettled accepted rows")
        if consumed_row_ids is not None and not set(consumed) <= set(consumed_row_ids):
            raise RuntimeError("v18 closure: consumed rows are missing from the saved checkpoint cursor")
        return {"status": "DRAINED_AND_SETTLED", "pending_requests": 0, "unconsumed_rows": 0,
                "accepted_rows": len(rows), "consumed_rows": len(consumed),
                "discarded_hold_rows": len(discarded) - len(quarantined), "quarantined_rows": len(quarantined),
                "row_settlements_sha256": _digest(self.row_settlements), "last_version": self.version}

    def state(self) -> dict:
        return {"plan_sha256": self.plan_sha256, "protocol_sha256": self.protocol_sha256,
                "version": self.version, "records": self.records, "history": self.history,
                "requests": self.requests, "closed": self.closed, "stages": self.stages,
                "committed": self.committed, "registry": self.sampler.live_registry(),
                "engine_steps": self.sampler.engine_steps, "pending": self.pending_descriptors(),
                "coexistence_reports": getattr(self.sampler, "coexistence_reports", []),
                **({"row_settlements": self.row_settlements} if self.v18 else {})}

    def save_drain_state(self, *, name: str = "drain-state.json") -> dict:
        if self._submitting or self.sampler.has_unfinished_requests() or set(self.requests) != set(self.closed):
            raise RuntimeError("v16b runtime: checkpoint requires a complete engine drain")
        state = self.state()
        journal = self.out / "requests.jsonl"
        state["journal_bytes"] = journal.stat().st_size if journal.exists() else 0
        state["journal_sha256"] = hashlib.sha256(journal.read_bytes() if journal.exists() else b"").hexdigest()
        envelope = {"state": state, "sha256": _digest(state)}
        _write(self.out / name, envelope)
        return envelope

    def restore_drain_state(self, path: Path) -> dict:
        if self.sampler.has_unfinished_requests():
            raise RuntimeError("v16b runtime: KV resume is forbidden")
        envelope = json.loads(Path(path).read_text())
        state = envelope["state"]
        if envelope["sha256"] != _digest(state) or state["plan_sha256"] != self.plan_sha256 or state["protocol_sha256"] != self.protocol_sha256:
            raise RuntimeError("v16b runtime: drain state or plan hash changed")
        if set(state["requests"]) != set(state["closed"]) or any(e["refcount"] for e in state["registry"].values()):
            raise RuntimeError("v16b runtime: saved state contains an open request")
        for descriptor in state["pending"]:
            if descriptor["output_sha256"] != _digest(state["closed"][descriptor["request_id"]]):
                raise RuntimeError("v16b runtime: sealed pending result changed")
        journal = self.out / "requests.jsonl"
        data = journal.read_bytes() if journal.exists() else b""
        size = state["journal_bytes"]
        if len(data) < size or hashlib.sha256(data[:size]).hexdigest() != state["journal_sha256"]:
            raise RuntimeError("v16b runtime: saved request journal changed")
        rollback_root = self.out / "rolled-back"
        rollback_prefix = f"after-{state['version']}"
        tails = []
        if rollback_root.exists():
            for archive in sorted(rollback_root.iterdir()):
                if archive.is_dir() and (archive.name == rollback_prefix or archive.name.startswith(rollback_prefix + "-")):
                    archived_journal = archive / "requests.jsonl"
                    if archived_journal.exists():
                        tails.append(archived_journal.read_bytes())
        tails.append(data[size:])
        for tail in tails:
            # Only newline-terminated records are durable; keep an interrupted UTF-8/JSON suffix as raw audit bytes.
            complete = tail[:tail.rfind(b"\n") + 1]
            for line in complete.splitlines():
                event = json.loads(line.decode("utf-8"))
                if event["status"] == "STARTED":
                    rid = event["request_id"]
                    pin = _pin(event)
                    if rid in self._rollback_started and self._rollback_started[rid] != pin:
                        raise RuntimeError("v16b runtime: archived rollback changed the original STARTED request")
                    self._rollback_started[rid] = pin
        extra_paths = []
        for prefix in ("rows-", "update-timing-"):
            for candidate in self.out.glob(prefix + "*.json"):
                index = candidate.name.removeprefix(prefix).split(".")[0]
                if index.isdigit() and int(index) >= state["version"]:
                    extra_paths.append(candidate)
        if len(data) > size or extra_paths:
            rollback_root.mkdir(parents=True, exist_ok=True)
            attempt = 1
            while True:
                rollback = rollback_root / (rollback_prefix if attempt == 1 else f"{rollback_prefix}-{attempt}")
                try:
                    rollback.mkdir()
                    break
                except FileExistsError:
                    attempt += 1
            (rollback / "requests.jsonl").write_bytes(data[size:])
            if (self.out / "items").exists():
                shutil.copytree(self.out / "items", rollback / "items")
            for candidate in extra_paths:
                shutil.move(str(candidate), str(rollback / candidate.name))
            with journal.open("wb") as stream:
                stream.write(data[:size])
                stream.flush()
                os.fsync(stream.fileno())
        for key in ("version", "records", "history", "requests", "closed", "stages", "committed"):
            setattr(self, key, state[key])
        if self.v18:
            self.row_settlements = state.get("row_settlements", {})
        self.sampler.engine_steps = state["engine_steps"]
        for pid, record in self.records.items():
            _write(self.out / "items" / (_digest(pid) + ".json"), {"problem_id": pid, **record})
        return state


def run_v16b(bundle: Any, optimizer: Any, scheduler_lr: Any, sampler: Any, plan: dict, *, out: Path,
             protocol: dict, items: Any, callbacks: RuntimeCallbacks, grade: Callable | None = None,
             verify: Callable | None = None, local_sequential: bool = False,
             runtime: V16bScheduler | None = None) -> dict:
    """Drive the fixed schedule; caller callbacks own training, checkpoint payloads and stop policy."""
    if callbacks.update is None or callbacks.checkpoint is None:
        raise ValueError("v16b runtime: real update and checkpoint callbacks are required")
    runtime = runtime or V16bScheduler(sampler, plan=plan, protocol=protocol, items=items, grade=grade,
        verify=verify, out=out, local_sequential=local_sequential, callbacks=callbacks)
    if runtime.version > runtime.last_update:
        if runtime.v18:
            runtime.terminal_closure()
        return {"status": "COMPLETE", "version": runtime.version, "updates": [], "state": runtime.state()}
    slot_started = time.perf_counter()
    generation_before = runtime.generation_seconds
    host_stage_before = dict(runtime.host_stage_seconds)
    admission_before = runtime.admission_wait_seconds
    sampler.add_version(bundle, runtime.version)
    while getattr(sampler, "_ready_outputs", None):
        runtime.step()
    runtime.submit_for_version(runtime.version)
    updates = []
    while runtime.version <= runtime.last_update:
        v = runtime.version
        while not runtime.ready_for_update(v):
            if not sampler.has_unfinished_requests():
                raise RuntimeError("v16b runtime: stalled schedule with no live requests")
            runtime.step()
        rows = runtime.rows_for_update(v)
        rl_rows = [r for r in rows if r.get("kind", r.get("generation", {}).get("kind")) in ("T1", "OBS", "RL", "OBS_RL")
                   or r.get("pg") is True]
        mixed = sum(bool(r.get("mixed_version", r.get("generation", {}).get("mixed_version"))) for r in rl_rows)
        contract = runtime.update_contract(v)
        if runtime.v17:
            mixed_all = sum(bool(r.get("mixed_version", r.get("generation", {}).get("mixed_version"))) for r in rows)
            if mixed_all:
                contract.update(external_hold="MIXED_VERSION", mixed_fraction=mixed_all / len(rows))
        elif rl_rows and mixed / len(rl_rows) > .05:
            contract.update(external_hold="MIXED_VERSION", mixed_fraction=mixed / len(rl_rows))
        with deterministic_update():
            update_started = time.perf_counter()
            stats = callbacks.update(v, rows, contract)
            update_seconds = time.perf_counter() - update_started
        runtime.settle_rows(v, rows, stats)
        runtime.commit_history(v)
        runtime.version += 1
        updates.append({"version": v, **stats})
        stop = list(callbacks.guard(v, stats) or []) if callbacks.guard is not None else []
        if (Path(out) / "STOP_REQUESTED").exists():
            stop.append("STOP_REQUESTED")
        if (Path(out) / "WATCHDOG_STOP").exists():
            stop.append("WATCHDOG_STOP")
        checkpoint_slot = runtime.version if runtime.v18b else protocol.get("prep_updates", 0) + runtime.version
        checkpoint = (bool(stop) or checkpoint_slot % 8 == 0 or v == runtime.last_update
                      or (runtime.v17 and (bool(stats.get("checkpoint_required")) or
                          (callbacks.checkpoint_due is not None and callbacks.checkpoint_due(v)))))
        checkpoint_seconds = drain_generation_seconds = 0.0
        if checkpoint:
            generation_before_drain = runtime.generation_seconds
            runtime.drain()
            drain_generation_seconds = runtime.generation_seconds - generation_before_drain
            checkpoint_started = time.perf_counter()
            if runtime.v18 and v == runtime.last_update and not stop:
                runtime.terminal_closure()
            state = runtime.save_drain_state()
            checkpoint_result = callbacks.checkpoint(v, state, runtime.pending_descriptors())
            if runtime.v17 and isinstance(checkpoint_result, dict):
                stop.extend(checkpoint_result.get("stop_reasons", []))
            checkpoint_seconds = time.perf_counter() - checkpoint_started
        wall_seconds = time.perf_counter() - slot_started
        generation_seconds = runtime.generation_seconds - generation_before
        timing = {"schema": "v16b-update-timing-v1", "version": v,
            "plan_sha256": runtime.plan_sha256, "protocol_sha256": runtime.protocol_sha256,
            "clock": "time.perf_counter", "boundary": "admission through update and optional checkpoint; receipt write excluded",
            "measurement": "host wall time; no CUDA synchronization or device utilization measurement",
            "wall_seconds": wall_seconds, "generation_seconds": generation_seconds,
            "drain_generation_seconds": drain_generation_seconds, "update_seconds": update_seconds,
            "checkpoint_seconds": checkpoint_seconds,
            "other_overhead_seconds": max(0.0, wall_seconds - generation_seconds - update_seconds - checkpoint_seconds),
            "idle_wait_seconds": 0.0,
            "idle_semantics": "no standalone idle wait; sampler.step waits count as generation; preparation and verification count as overhead",
            "checkpoint": checkpoint}
        if runtime.v17:
            timing.update(schema="v17-update-timing-v1",
                          host_stage_seconds={k: value - host_stage_before[k] for k, value in runtime.host_stage_seconds.items()},
                          host_stage_semantics="per-slot host wall deltas; nested preparation/validation are not device timings",
                          admission_wait_seconds=runtime.admission_wait_seconds - admission_before,
                          gpu_seconds=stats.get("gpu_seconds"),
                          gpu_timing_semantics="null unless measured by the update callback with device synchronization",
                          negative_candidate_tokens=stats.get("t1_negative_candidate_tokens"),
                          negative_retained_tokens=stats.get("t1_negative_retained_tokens"),
                          negative_retained_ratio=stats.get("t1_negative_retained_ratio"),
                          loop_confirmed=stats.get("loop_confirmed"),
                          loop_tokens_penalized=stats.get("loop_tokens_penalized"),
                          length_nonloop_excluded=stats.get("length_nonloop_excluded"))
            if runtime.v18:
                timing.update(schema="v18-update-timing-v1", note_update_alignment=stats.get("note_update_alignment"),
                              policy_mask_counts=stats.get("policy_mask_counts"),
                              consumed_row_ids=stats.get("consumed_row_ids"),
                              component_gradient_norms=stats.get("component_gradient_norms"),
                              note_parent_gradient_norms=stats.get("note_parent_gradient_norms"))
            if hasattr(sampler, "heartbeat_v17") and not local_sequential:
                sampler.admission_wait_seconds = runtime.admission_wait_seconds
                timing["train_KV"] = sampler.heartbeat_v17()
        timing_path = runtime.out / f"update-timing-{v}.json"
        if timing_path.exists():
            raise RuntimeError("v16b runtime: sealed update timing already exists")
        _write(timing_path, {"timing": timing, "sha256": _digest(timing)})
        if stop or v == runtime.last_update:
            return {"status": "STOPPED" if stop else "COMPLETE", "version": runtime.version,
                    "stop_reasons": stop, "updates": updates, "state": runtime.state()}
        slot_started = time.perf_counter()
        generation_before = runtime.generation_seconds
        host_stage_before = dict(runtime.host_stage_seconds)
        admission_before = runtime.admission_wait_seconds
        sampler.add_version(bundle, runtime.version)
        while getattr(sampler, "_ready_outputs", None):
            runtime.step()
        runtime.submit_for_version(runtime.version)
    raise AssertionError("v16b runtime: unreachable schedule exit")
