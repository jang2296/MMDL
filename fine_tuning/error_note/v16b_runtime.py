def _digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":"), allow_nan=False).encode()).hexdigest()


OBS_TASK_V18 = "v18-single-fact-observation-v1"


def observation_baseline_v18(layer: str, history: list[dict], *, history_cutoff: int,
                              prior: dict | None = None) -> dict:
    """A binary-task prior never borrows old list-F1 or ungraded observations."""
    if type(history_cutoff) is not int or history_cutoff < -2:
        raise ValueError("v18 observation baseline: explicit delayed history cutoff required")
    selected = []
    for entry in history:
        if (entry.get("kind") != "OBS" or entry.get("task") != OBS_TASK_V18
                or entry.get("layer") != layer or entry.get("committed") is not True
                or entry.get("pg") is not True):
            continue
        block = entry.get("block", entry.get("block_index"))
        if type(block) is not int or block > history_cutoff:
            continue
        reward = entry.get("reward")
        if isinstance(reward, bool) or reward not in (0, 1):
            raise ValueError("v18 observation baseline: binary graded history required")
        selected.append(entry)
    window = selected[-32:]
    body = {"version": "v18-obs-baseline-v1", "task": OBS_TASK_V18, "layer": layer,
            "initial": .5, "baseline": (8 * .5 + sum(e["reward"] for e in window)) / (8 + len(window)),
            "zero_advantage": False, "window_count": len(window), "history_cutoff": history_cutoff,
            "history_sha256": _digest(selected), "prior_sha256": _digest(prior)}
    return body | {"sha256": _digest(body)}


# Rolled-back requests must keep their plan identity; texts, policy hashes and baseline receipts are regenerated by a
# nondeterministic engine after resume, so they stay in the journal as an audit record only.
_PIN = ("request_id", "problem_id", "block_id", "stage", "seed", "max_tokens", "kind", "policy_version",
        "protocol_sha256", "sampling")


def _pin(event: dict) -> dict:
    return {key: event[key] for key in _PIN if key in event}


def _write(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        json.dump(value, stream, ensure_ascii=False, sort_keys=True, allow_nan=False)
        stream.write("\n")
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


@contextmanager
def deterministic_update():
    """The sole update boundary: vLLM steps use nondeterministic kernels outside this scope."""
    import torch

    previous = torch.are_deterministic_algorithms_enabled()
    torch.use_deterministic_algorithms(True)
    try:
        yield
    finally:
        torch.use_deterministic_algorithms(previous)


def kv_budget_v16b(extra_reserved_gib: float) -> float:
    import math

    if not math.isfinite(extra_reserved_gib) or extra_reserved_gib < 0:
        raise ValueError("v16b capacity: finite measured nonnegative extra reserved GiB required")
    budget = min(24.0, 52.8 - extra_reserved_gib)
    if budget < 16.0:
        raise RuntimeError("v16b capacity: measured update leaves less than 16 GiB for KV")
    return budget


def reserve_request_v17(prepared: dict, actual_kv_tokens: int, block_size: int,
                        live_reservations: list[int], *, active: int, ceiling: int = 16) -> dict:
    """Reserve the entire prepared prompt and future completion, including native waiting requests."""
    values = (actual_kv_tokens, block_size, ceiling)
    if any(type(v) is not int or v < 1 for v in values) or ceiling > 16:
        raise ValueError("v17 capacity: positive measured KV, block size and ceiling <=16 required")
    prompt, cap = prepared["prompt_tokens"], prepared["max_tokens"]
    if (type(prompt) is not int or prompt < 0 or type(cap) is not int or cap < 1
            or type(active) is not int or active < 0 or active != len(live_reservations)
            or any(type(v) is not int or v < 1 or v % block_size for v in live_reservations)):
        raise ValueError("v17 capacity: exact prompt, cap and live reservation ledger required")
    usable = actual_kv_tokens * 9 // 10
    reserve = ((prompt + cap + block_size - 1) // block_size) * block_size
    if reserve > usable:
        raise RuntimeError("CAPACITY_INSUFFICIENT: one full request exceeds actual usable training KV")
    reserved = sum(live_reservations)
    if reserved > usable or active > ceiling:
        raise RuntimeError("v17 capacity: live reservation ledger exceeds capacity")
    return {"version": "full-request-reservation-v1", "train_KV_capacity": actual_kv_tokens,
            "usable_tokens": usable, "block_size": block_size, "request_reserved_tokens": reserve,
            "reserved_tokens": reserved, "active": active, "ceiling": ceiling,
            "status": "ADMIT" if active < ceiling and reserved + reserve <= usable else "WAIT"}

